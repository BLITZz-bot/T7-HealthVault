      return '''🩺 $name ($age సం.) వారి AI ఆరోగ్య విశ్లేషణ:
• NEWS2 హెచ్చరిక స్కోరు: $news2Score (${news2Result['risk_level']})
• సెప్సిస్ రిస్క్ రేటు: $sepsisScore ($sepsisLevel)
${criticalDeltas.isNotEmpty ? '• ముఖ్యమైన మార్పులు: ${criticalDeltas.join(', ')}\n' : ''}
📋 సలహా: ${news2Result['action']}''';

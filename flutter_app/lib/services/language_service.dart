• செப்சிஸ் அபாய விகிதம்: $sepsisScore ($sepsisLevel)
${criticalDeltas.isNotEmpty ? '• முக்கியமான மாற்றங்கள்: ${criticalDeltas.join(', ')}\n' : ''}
📋 பரிந்துரை: ${news2Result['action']}''';

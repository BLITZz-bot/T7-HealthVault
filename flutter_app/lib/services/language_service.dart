  /// Generate a culturally attuned clinical summary in the selected language
  static String generateClinicalExplanation({
    required Map<String, dynamic> member,
    required Map<String, dynamic> news2Result,
    required Map<String, dynamic> sepsisResult,
    required Map<String, Map<String, dynamic>> delta,
    required String languageCode,
  }) {
    final name = member['full_name'] ?? 'Member';
    final age = member['age']?.toString() ?? '';
    final news2Score = news2Result['score'] ?? 0;
    final sepsisScore = sepsisResult['risk_percent'] ?? '0%';
    final sepsisLevel = sepsisResult['risk_level'] ?? 'Low Risk';

    final List<String> criticalDeltas = [];
    delta.forEach((k, v) {
      final diff = v['diff'] as num?;
      if (diff != null && diff.abs() > 0) {
        final sign = diff > 0 ? '+' : '';
        criticalDeltas.add('$k: $sign$diff ${v['unit']}');
      }
    });

    if (languageCode == 'hi') {
      return '''🩺 $name ($age वर्ष) का एआई स्वास्थ्य विश्लेषण:
• NEWS2 चेतावनी स्कोर: $news2Score (${news2Result['risk_level']})
• सेप्सिस जोखिम दर: $sepsisScore ($sepsisLevel)
${criticalDeltas.isNotEmpty ? '• महत्वपूर्ण बदलाव: ${criticalDeltas.join(', ')}\n' : ''}
📋 सिफारिश: ${news2Result['action']}''';
    } else if (languageCode == 'kn') {
      return '''🩺 $name ($age ವರ್ಷ) ರ AI ಆರೋಗ್ಯ ವಿಶ್ಲೇಷಣೆ:

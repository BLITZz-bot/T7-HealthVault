  static Future<void> init() async {
    final prefs = await SharedPreferences.getInstance();
    final lang = prefs.getString(_prefKeyLanguage) ?? 'en';
    currentLanguageNotifier.value = lang;
    // Load persisted downloaded languages
    final downloaded = prefs.getStringList(_prefKeyDownloadedLangs) ?? [];
    downloadedLanguagesNotifier.value = Set<String>.from(downloaded);
  }

  static String get currentLanguage => currentLanguageNotifier.value;

  static Future<bool> isFirstRun() async {
    final prefs = await SharedPreferences.getInstance();
    return !(prefs.getBool(_prefKeyFirstRunDone) ?? false);
  }

  static Future<void> completeFirstRun() async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setBool(_prefKeyFirstRunDone, true);
  }

  static Future<void> setLanguage(String code) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_prefKeyLanguage, code);
    currentLanguageNotifier.value = code;
  }

  /// Returns true if a downloadable language pack is available (downloaded)
  static bool isLanguageDownloaded(String code) {
    // Built-in languages are always available
    if (supportedLanguages.any((l) => l['code'] == code)) return true;
    return downloadedLanguagesNotifier.value.contains(code);
  }

  /// Download a language pack (simulates download, then unlocks the language locally)
  static Future<bool> downloadLanguagePack(String code) async {
    if (downloadingLanguageNotifier.value != null) return false; // already downloading
    downloadingLanguageNotifier.value = code;
    langDownloadProgressNotifier.value = 0.0;

    try {
      // Simulate realistic language pack download with progress
      final steps = [0.1, 0.22, 0.35, 0.48, 0.61, 0.74, 0.85, 0.93, 1.0];
      for (final step in steps) {
        await Future.delayed(const Duration(milliseconds: 280));
        langDownloadProgressNotifier.value = step;
      }

      // Persist downloaded state
      final prefs = await SharedPreferences.getInstance();
      final current = Set<String>.from(downloadedLanguagesNotifier.value);
      current.add(code);
      downloadedLanguagesNotifier.value = current;
      await prefs.setStringList(_prefKeyDownloadedLangs, current.toList());

      return true;
    } catch (_) {
      return false;
    } finally {
      downloadingLanguageNotifier.value = null;
      langDownloadProgressNotifier.value = 0.0;
    }
  }

  /// Delete a downloaded language pack
  static Future<void> deleteLanguagePack(String code) async {
    final prefs = await SharedPreferences.getInstance();
    final current = Set<String>.from(downloadedLanguagesNotifier.value);
    current.remove(code);
    downloadedLanguagesNotifier.value = current;
    await prefs.setStringList(_prefKeyDownloadedLangs, current.toList());
    // If active language was deleted, switch to English
    if (currentLanguage == code) {
      await setLanguage('en');
    }
  }

  /// Returns language info from either built-in or downloadable list
  static Map<String, String> getLanguageInfo(String code) {
    final builtin = supportedLanguages.firstWhere(
      (l) => l['code'] == code,
      orElse: () => const {},
    );
    if (builtin.isNotEmpty) return builtin;
    return downloadableLanguages.firstWhere(
      (l) => l['code'] == code,
      orElse: () => supportedLanguages.first,
    );
  }


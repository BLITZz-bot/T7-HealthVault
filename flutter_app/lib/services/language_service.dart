• ಸೆಪ್ಸಿಸ್ ಅಪಾಯದ ಪ್ರಮಾಣ: $sepsisScore ($sepsisLevel)
${criticalDeltas.isNotEmpty ? '• ಪ್ರಮುಖ ಬದಲಾವಣೆಗಳು: ${criticalDeltas.join(', ')}\n' : ''}
